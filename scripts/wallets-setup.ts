/**
 * Creates and prepares the dedicated Stellar TESTNET wallets Borderless needs.
 *
 *  - Agent payer wallet: Friendbot XLM, USDC trustline, testnet USDC (via a testnet DEX swap).
 *  - Empty demo wallet: XLM + USDC trustline, no USDC (the insufficient-funds scenario).
 *  - Household treasury (Funding guard): Friendbot XLM, USDC trustline, 5 testnet USDC.
 *  - One receiving wallet per demo provider: Friendbot XLM + USDC trustline.
 *
 * Idempotent: existing keys in .env.local are reused; funded accounts are not re-funded.
 * Secret keys are written ONLY to .env.local (git-ignored) and are never printed.
 *
 * Usage: pnpm wallets:setup [--usdc-target 20]
 */
import "./_env";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { Asset, BASE_FEE, Horizon, Keypair, Networks, Operation, TransactionBuilder } from "@stellar/stellar-sdk";

const HORIZON_URL = process.env.STELLAR_HORIZON_URL ?? "https://horizon-testnet.stellar.org";
const FRIENDBOT_URL = "https://friendbot.stellar.org";
const USDC = new Asset("USDC", "GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5");
const ENV_FILE = ".env.local";

const args = process.argv.slice(2);
const targetIdx = args.indexOf("--usdc-target");
const USDC_TARGET = targetIdx >= 0 ? Number(args[targetIdx + 1]) : 20;

const horizon = new Horizon.Server(HORIZON_URL);

interface WalletSpec {
  label: string;
  secretVar: string;
  publicVar: string;
  needsUsdc: boolean;
  /** Testnet USDC to hold (defaults to --usdc-target). */
  usdcTarget?: number;
}

const WALLETS: WalletSpec[] = [
  { label: "Agent payer", secretVar: "AGENT_STELLAR_SECRET", publicVar: "AGENT_STELLAR_PUBLIC", needsUsdc: true },
  { label: "Empty demo wallet", secretVar: "DEMO_EMPTY_WALLET_SECRET", publicVar: "DEMO_EMPTY_WALLET_PUBLIC", needsUsdc: false },
  { label: "Household treasury", secretVar: "TREASURY_STELLAR_SECRET", publicVar: "TREASURY_STELLAR_PUBLIC", needsUsdc: true, usdcTarget: 5 },
  { label: "Electricity provider", secretVar: "PROVIDER_ELECTRICITY_SECRET", publicVar: "PROVIDER_ELECTRICITY_PAYTO", needsUsdc: false },
  { label: "Airtime provider", secretVar: "PROVIDER_AIRTIME_SECRET", publicVar: "PROVIDER_AIRTIME_PAYTO", needsUsdc: false },
  { label: "Data provider", secretVar: "PROVIDER_DATA_SECRET", publicVar: "PROVIDER_DATA_PAYTO", needsUsdc: false },
  { label: "PowerGrid provider", secretVar: "PROVIDER_POWERGRID_SECRET", publicVar: "PROVIDER_POWERGRID_PAYTO", needsUsdc: false },
  { label: "TopUp Hub provider", secretVar: "PROVIDER_TOPUPHUB_SECRET", publicVar: "PROVIDER_TOPUPHUB_PAYTO", needsUsdc: false },
  { label: "DataLink provider", secretVar: "PROVIDER_DATALINK_SECRET", publicVar: "PROVIDER_DATALINK_PAYTO", needsUsdc: false },
];

// ── .env.local handling (preserves unrelated lines) ─────────────────────────
function readEnvFile(): Map<string, string> {
  const map = new Map<string, string>();
  if (!existsSync(ENV_FILE)) return map;
  for (const line of readFileSync(ENV_FILE, "utf8").split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) map.set(m[1]!, m[2]!);
  }
  return map;
}

function writeEnvFile(updates: Record<string, string>) {
  const existing = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, "utf8").split(/\r?\n/) : [];
  const remaining = { ...updates };
  const lines = existing.map((line) => {
    const m = /^([A-Z0-9_]+)=/.exec(line.trim());
    if (m && m[1]! in remaining) {
      const v = remaining[m[1]!]!;
      delete remaining[m[1]!];
      return `${m[1]}=${v}`;
    }
    return line;
  });
  const extra = Object.entries(remaining);
  if (extra.length) {
    if (lines.length && lines[lines.length - 1] !== "") lines.push("");
    lines.push("# Stellar TESTNET demo wallets — generated by `pnpm wallets:setup`. Never commit.");
    for (const [k, v] of extra) lines.push(`${k}=${v}`);
  }
  writeFileSync(ENV_FILE, lines.join("\n").replace(/\n*$/, "\n"), { mode: 0o600 });
}

// ── Stellar helpers ─────────────────────────────────────────────────────────
async function loadAccount(publicKey: string) {
  try {
    return await horizon.loadAccount(publicKey);
  } catch (err: unknown) {
    if ((err as { response?: { status?: number } }).response?.status === 404) return null;
    throw err;
  }
}

async function friendbot(publicKey: string) {
  const res = await fetch(`${FRIENDBOT_URL}/?addr=${encodeURIComponent(publicKey)}`);
  if (!res.ok) throw new Error(`Friendbot failed (${res.status}): ${(await res.text()).slice(0, 200)}`);
}

function usdcBalance(account: Horizon.AccountResponse): number | null {
  const line = account.balances.find(
    (b) => "asset_code" in b && b.asset_code === USDC.code && "asset_issuer" in b && b.asset_issuer === USDC.issuer,
  );
  return line ? Number(line.balance) : null;
}

function xlmBalance(account: Horizon.AccountResponse): number {
  const native = account.balances.find((b) => b.asset_type === "native");
  return native ? Number(native.balance) : 0;
}

async function submit(kp: Keypair, build: (b: TransactionBuilder) => TransactionBuilder) {
  const account = await horizon.loadAccount(kp.publicKey());
  const tx = build(new TransactionBuilder(account, { fee: BASE_FEE, networkPassphrase: Networks.TESTNET }))
    .setTimeout(60)
    .build();
  tx.sign(kp);
  return horizon.submitTransaction(tx);
}

async function acquireUsdc(kp: Keypair, needed: number) {
  // Find how much XLM buys `needed` USDC, then strict-receive with a 10% slippage cap.
  const paths = await horizon.strictReceivePaths([Asset.native()], USDC, needed.toFixed(7)).call();
  const best = paths.records.sort((a, b) => Number(a.source_amount) - Number(b.source_amount))[0];
  if (!best) throw new Error("No testnet DEX path from XLM to USDC right now. Use https://faucet.circle.com (Stellar Testnet) instead.");
  const sendMax = (Number(best.source_amount) * 1.1).toFixed(7);
  const path = best.path.map((p) => (p.asset_type === "native" ? Asset.native() : new Asset(p.asset_code, p.asset_issuer)));
  await submit(kp, (b) =>
    b.addOperation(
      Operation.pathPaymentStrictReceive({
        sendAsset: Asset.native(),
        sendMax,
        destination: kp.publicKey(),
        destAsset: USDC,
        destAmount: needed.toFixed(7),
        path,
      }),
    ),
  );
  return Number(best.source_amount);
}

// ── Main ────────────────────────────────────────────────────────────────────
async function main() {
  console.log("Borderless — Stellar TESTNET wallet setup (testnet assets have no real-world value)\n");
  const env = readEnvFile();
  const updates: Record<string, string> = {};

  for (const spec of WALLETS) {
    let secret = env.get(spec.secretVar) ?? process.env[spec.secretVar];
    if (!secret || !/^S[A-Z2-7]{55}$/.test(secret)) {
      secret = Keypair.random().secret();
      updates[spec.secretVar] = secret;
    }
    const kp = Keypair.fromSecret(secret);
    updates[spec.publicVar] = kp.publicKey();
    // Persist keys immediately so a later failure never loses a generated secret.
    writeEnvFile(updates);

    let account = await loadAccount(kp.publicKey());
    if (!account) {
      process.stdout.write(`  ${spec.label}: funding with Friendbot… `);
      await friendbot(kp.publicKey());
      account = await horizon.loadAccount(kp.publicKey());
      console.log("done");
    }

    if (usdcBalance(account) === null) {
      process.stdout.write(`  ${spec.label}: adding USDC trustline… `);
      await submit(kp, (b) => b.addOperation(Operation.changeTrust({ asset: USDC })));
      account = await horizon.loadAccount(kp.publicKey());
      console.log("done");
    }

    if (spec.needsUsdc) {
      const current = usdcBalance(account) ?? 0;
      const target = spec.usdcTarget ?? USDC_TARGET;
      if (current < target) {
        const needed = Number((target - current).toFixed(7));
        process.stdout.write(`  ${spec.label}: swapping testnet XLM for ${needed} testnet USDC on the testnet DEX… `);
        const spent = await acquireUsdc(kp, needed);
        account = await horizon.loadAccount(kp.publicKey());
        console.log(`done (~${spent.toFixed(2)} XLM)`);
      }
    }

    console.log(
      `✓ ${spec.label.padEnd(22)} ${kp.publicKey()}  XLM ${xlmBalance(account).toFixed(2).padStart(10)}  USDC ${(usdcBalance(account) ?? 0).toFixed(2).padStart(8)}`,
    );
  }

  console.log(`\nKeys saved to ${ENV_FILE} (git-ignored). Secrets were not printed.`);
}

main().catch((err) => {
  const detail = (err as { response?: { data?: { extras?: unknown } } }).response?.data?.extras;
  console.error("\nWallet setup failed:", err instanceof Error ? err.message : err, detail ? JSON.stringify(detail) : "");
  process.exit(1);
});
